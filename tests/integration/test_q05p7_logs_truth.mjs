import assert from 'node:assert/strict';
import fs from 'node:fs';
const app=fs.readFileSync('module/webroot/app.js','utf8');
const match=app.match(/function normalizeBackendLogs\(value\) \{[\s\S]*?\n\}/);
assert.ok(match,'missing native log adaptation');
const normalize = new Function(`${match[0]};return normalizeBackendLogs;`)();
const real=[{timestamp:'2026-10-11T21:37:47.606470086Z',level:'WARN',source:'rpc',code:'OPERATION',message:'operation=mount.start outcome=operation_failed'},{timestamp:'2026-10-11T21:37:47Z',level:'ERROR',source:'mount',code:'MOUNT_START_FAILED',message:'FUSE readiness/mount identity not observed (provider_permission_denied)'}];
const records=normalize(real);
assert.equal(records.length,2);
assert.equal(records[0].severity,'WARN');
assert.equal(records[1].severity,'ERROR');
assert.ok(records[0].time_unix_ms>0);
assert.equal(records[1].source,'mount');
assert.equal(normalize({records:[{time_unix_ms:10000,severity:'INFO',message:'old'}]}).length,1);
assert.throws(()=>normalize({unexpected:real}),/Invalid diagnostics/);
assert.throws(()=>normalize(null),/Invalid diagnostics/);
assert.ok(app.includes('state.logRecords=normalizeBackendLogs(value)'));
assert.ok(!app.includes('state.logRecords=value.records||[]'));
console.log('SB-Q05P7 native diagnostics array, timestamp and severity parity PASS');
