import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createLiveFeed,consumeLivePage,latestLiveJobs,formatLiveProgress,throughputSeries} from '../../module/webroot/live_progress.js';
const id='a'.repeat(32);let f=createLiveFeed();
const ev=(seq,p)=>({sequence:seq,unix_millis:1000+seq*1000,operation_id:id,run_id:id,type:'job.progress',state:'running',phase:'transferring',progress:p});
const page=(events,end)=>({schema_version:1,events,next_cursor:end,latest_cursor:end});
consumeLivePage(f,page([ev(1,{bytes:1000,total_bytes:4000,percent:25,files_done:1,files_total:4,checks_done:7,checks_total:9,errors:2,retry_error:true,speed_bytes_per_second:200,eta_seconds:15})],1));
let job=latestLiveJobs(f)[0];
assert.equal(job.percent,25);assert.equal(job.totalBytes,4000);assert.equal(job.filesDone,1);assert.equal(job.filesTotal,4);
assert.equal(job.retryError,true);assert.equal(job.transferRetries,null);
assert.match(formatLiveProgress(job,n=>`${n}B`),/1000B \/ 4000B transferred.*25.0%.*1 \/ 4 transfers.*7 \/ 9 checks.*2 rclone errors.*retry count not reported/i);
consumeLivePage(f,page([ev(2,{bytes:3000,total_bytes:4000,percent:75,files_done:3,files_total:4,transfer_retries:2,speed_bytes_per_second:400})],2));
assert.deepEqual(throughputSeries(f,id),[{time:2000,bytesPerSecond:200},{time:3000,bytesPerSecond:400}]);
assert.equal(throughputSeries(f,'/invalid').length,0);
assert.equal(throughputSeries(f,id,1).length,1);
job=latestLiveJobs(f)[0];assert.match(formatLiveProgress(job,n=>`${n}B`),/2 retries/);
consumeLivePage(f,page([ev(3,{bytes:3000,speed_bytes_per_second:0})],3));
assert.equal(latestLiveJobs(f)[0].percent,null);
assert.doesNotMatch(formatLiveProgress(latestLiveJobs(f)[0],n=>`${n}B`),/%|\/ 0B/);
assert.equal(throughputSeries(f,id).length,3);
for(let i=4;i<170;i++)consumeLivePage(f,page([ev(i,{bytes:i*100,speed_bytes_per_second:i})],i));
assert.equal(f.records.length,96);assert.ok(throughputSeries(f,id).length<=24);
const ui=fs.readFileSync(new URL('../../module/webroot/app.js',import.meta.url),'utf8');
assert.match(ui,/aria-valuenow/);assert.match(ui,/phase-a-live-sparkline/);
assert.doesNotMatch(ui,/innerHTML\s*=/);
console.log('Phase A3 progress totals, truthful retries, bounded throughput replay, accessible UI: PASS');
