import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createTransferDraft,changeTransfer,transferSpec,acceptTransferPreview,readyTransfer,redactRunId,validFolderEndpoint} from '../../module/webroot/remote_transfer_ui.js';
const d=createTransferDraft();
assert.equal(transferSpec(d),null);
for(const bad of ['drive:','drive:/root','drive:../p','drive:a/../b','drive:dir\\abc','drive:file\nname','unknown:dir/','local/path','drive:dir//two','drive:dir/:name'])assert.equal(validFolderEndpoint(bad),false,bad);
for(const good of ['drive:Photos','a:album/2026','crypt.remote:Backups'])assert.equal(validFolderEndpoint(good),true,good);
changeTransfer(d,'source','drive:Photos');changeTransfer(d,'destination','drive:Backup');
let spec=transferSpec(d);assert.equal(spec.kind,'copy');
let revision=d.revision;
const response={...spec,proof:'verified-backend-proof',expires_seconds:120,copies_skip_existing:true,read_only:false};
assert.equal(acceptTransferPreview(d,revision,spec,response),true);
assert.equal(readyTransfer(d).proof,'verified-backend-proof');
changeTransfer(d,'destination','drive:Backup/New');assert.equal(readyTransfer(d),null);
assert.equal(acceptTransferPreview(d,revision,spec,response),false,'stale preview must not restore proof');
changeTransfer(d,'destination','drive:Photos/sub');assert.equal(transferSpec(d),null,'overlapping folders must fail');
changeTransfer(d,'destination','archive:Backup');spec=transferSpec(d);
assert.equal(acceptTransferPreview(d,d.revision,spec,{...response,destination:'archive:Backup'}),true);
assert.equal(readyTransfer(d).kind,'copy');
changeTransfer(d,'kind','check');spec=transferSpec(d);
assert.equal(acceptTransferPreview(d,d.revision,spec,{...spec,proof:'verified-backend-proof',expires_seconds:120,copies_skip_existing:false,read_only:true}),true);
assert.equal(readyTransfer(d).kind,'check');
assert.equal(acceptTransferPreview(d,d.revision,spec,{...spec,proof:'verified-backend-proof',expires_seconds:120,copies_skip_existing:true,read_only:true}),false);
assert.equal(redactRunId('a'.repeat(32)),'a'.repeat(32));assert.equal(redactRunId('xyz'),null);
const app=fs.readFileSync(new URL('../../module/webroot/app.js',import.meta.url),'utf8');
const ui=fs.readFileSync(new URL('../../module/webroot/index.html',import.meta.url),'utf8');
assert.match(app,/preview\('remote.transfer.preview',spec\)/);
assert.match(app,/run\('remote.transfer.start',payload\)/);
assert.match(app,/for \(const run of snapshot.runs\|\|\[\]\)/);
assert.match(app,/state.activeView==='remotes'/);
assert.match(app,/if \(view==='remotes'\) return byId\('remoteTransferLive'\)/);
assert.match(app,/\['jobs','activity','remotes'\].includes\(state.activeView\)/);
assert.match(app,/if\(!globalThis.confirm\(message\)\)return/);
assert.match(app,/draft.proof=null;state.remoteTransferBusy=true/);
assert.match(app,/if\(!acceptTransferPreview\(draft,revision,spec,response\)\)/);
assert.doesNotMatch(app,/query\('rclone\.rc'/);
for(const id of ['remoteTransferKind','remoteTransferPreview','remoteTransferStart','remoteTransferLive','remoteUseTransferSource'])assert.ok(ui.includes(`id="${id}"`));
console.log('Phase B2 remote transfer selection, preview proof, stale-response/cancellation and UI integration: PASS');
